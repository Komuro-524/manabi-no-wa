-- ---------------------------------------------------------------------
-- ✅ 00  RLS が全テーブルで有効か（これだけは SQL Editor で確認できる）
--        期待：13行すべて rowsecurity = true
-- ---------------------------------------------------------------------
select relname as テーブル, relrowsecurity as rls有効
from   pg_class
where  relnamespace = 'public'::regnamespace
  and  relkind = 'r'
order  by relname;


-- ---------------------------------------------------------------------
-- ✅ 01  他人の非公開タグが見えない
--        期待：0件
-- ---------------------------------------------------------------------
select count(*) as 見えてはいけない件数
from   user_tags
where  visibility = 'private'
  and  user_id <> auth.uid();


-- ---------------------------------------------------------------------
-- ✅ 02  候補タグ・提案中のタグが一般社員に見えない
--        期待：0件（管理者で実行すると見えるのが正しい）
-- ---------------------------------------------------------------------
select count(*) as 見えてはいけない件数
from   tags
where  status in ('candidate','proposed','rejected','banned');


-- ---------------------------------------------------------------------
-- ✅ 03  企て・判断ログ・実行記録が一般社員に見えない
--        期待：すべて0件
-- ---------------------------------------------------------------------
select (select count(*) from quests)      as 企て,
       (select count(*) from quest_steps) as 判断ログ,
       (select count(*) from agent_runs)  as 実行記録;


-- ---------------------------------------------------------------------
-- ✅ 04  自分を管理者にできない
--        期待：エラー または 0行更新
-- ---------------------------------------------------------------------
update users set role = 'admin' where id = auth.uid();


-- ---------------------------------------------------------------------
-- ✅ 05  自分のタグの強さを盛れない
--        期待：エラー または 0行更新
--        （公開設定だけは set_tag_visibility() で変えられる）
-- ---------------------------------------------------------------------
update user_tags set strength = 999 where user_id = auth.uid();


